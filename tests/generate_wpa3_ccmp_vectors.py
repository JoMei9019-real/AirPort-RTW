#!/usr/bin/env python3
"""Offline fixture generator; requires PyCA cryptography, not needed by CI.

AESCCM independently computes CCMP ciphertext and eight-byte tags. Keep hashes
of complete frames so the checked-in fixture covers large MPDUs compactly.
Run from any directory to regenerate wpa3_ccmp_vectors.hpp alongside this file.
"""
import hashlib
from pathlib import Path
from cryptography.hazmat.primitives.ciphers.aead import AESCCM

lengths = [0, 1, 2, 7, 15, 16, 17, 31, 32, 33, 255, 256, 257,
           1499, 1500, 1501, 8191, 8192]
numbers = [1, 256, 65535, 0x010203040506, 0xffffffffffff]
lines = ['// Generated by generate_wpa3_ccmp_vectors.py using PyCA AESCCM.',
         '// Each SHA-256 covers the entire encrypted 802.11 frame.',
         'static const char*const ccmpAnswers[]={']
index = 0
for kind in range(3):
    for length in lengths:
        qos, mgmt = kind == 0, kind == 2
        h = 26 if qos else 24
        frame = bytearray(h + 16 + length)
        frame[0], frame[1] = (0xd0, 0x40) if mgmt else ((0x88 if qos else 8), 0x42)
        frame[4:22] = bytes((2 + i * 7) & 255 for i in range(18))
        frame[22:24] = b'\x50\x12'
        if qos:
            frame[24] = index % 16
        pn = numbers[index % len(numbers)]
        little = pn.to_bytes(6, 'little')
        frame[h:h+8] = little[:2] + bytes([0, 0x20 | ((index % 4) << 6)]) + little[2:]
        key = bytes((i * 13 + index * 11) & 255 for i in range(16))
        plain = bytes((i * 37 + index * 19) & 255 for i in range(length))
        nonce = bytes([0x10 if mgmt else frame[24] if qos else 0]) + frame[10:16] + pn.to_bytes(6, 'big')
        aad = bytes([frame[0] & (0xff if mgmt else 0x8f), frame[1] & 0xc7]) + frame[4:22] + b'\0\0'
        if qos:
            aad += bytes([frame[24], 0])
        frame[h+8:] = AESCCM(key, tag_length=8).encrypt(nonce, plain, aad)
        lines.append('    "' + hashlib.sha256(frame).hexdigest() + '",')
        index += 1
lines.append('};\n')
Path(__file__).with_name('wpa3_ccmp_vectors.hpp').write_text('\n'.join(lines))
